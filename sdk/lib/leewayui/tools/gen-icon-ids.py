#!/usr/bin/env python3
# Generate sdk/include/leewayui/ribbon_icons.h (public enum) and
# sdk/lib/leewayui/aureline_slugs.inc (private id->"app/slug" table) from the
# Aureline masters in shell/appframework/icons/<app>/. Run and commit the diff.
import os,sys,re
ICONS=sys.argv[1] if len(sys.argv)>1 else os.path.join(os.path.dirname(__file__),
      "../../../../shell/appframework/icons")
HERE=os.path.dirname(__file__)
HDR=os.path.join(HERE,"../../../include/leewayui/ribbon_icons.h")
INC=os.path.join(HERE,"../aureline_slugs.inc")
apps=[("common",0x0100),("paint",0x0200),("viewer",0x0300),("wordpad",0x0400)]
def slugs(app):
    d=os.path.join(ICONS,app); s=set()
    if os.path.isdir(d):
        for f in os.listdir(d):
            m=re.match(r'aur\.'+app+r'\.([a-z0-9-]+)@(?:16|32|mono)\.svg$',f)
            if m: s.add(m.group(1))
    return sorted(s)
h=["/*"," * PROJECT:     LeewayUI"," * LICENSE:     LGPL-2.1-or-later",
   " * PURPOSE:     Aureline ribbon icon ids (G10). Stable ids an app stores in",
   " *              LeewayUICommand.icon_id; the stock resolver maps each to its",
   " *              Aureline master at 16/32 px + a mono variant.",
   " *              GENERATED by sdk/lib/leewayui/tools/gen-icon-ids.py - do not edit.",
   " * COPYRIGHT:   Copyright 2026 Leeway Open Software"," */","#pragma once","#include <stdint.h>","",
   "/* ranges: common 0x0100, paint 0x0200, viewer 0x0300, wordpad 0x0400. */",""]
inc=["/* GENERATED by tools/gen-icon-ids.py: icon_id -> \"app/slug\". Do not edit. */",
     "static const struct { uint32_t id; const char *rel; } kAurelineSlugs[] = {"]
n=0
for app,base in apps:
    sl=slugs(app)
    if not sl: continue
    h.append("/* --- %s (%d) --- */"%(app,len(sl)))
    for i,s in enumerate(sl):
        name="LWUI_AUR_%s_%s"%(app.upper(),s.upper().replace('-','_'))
        h.append("#define %-32s 0x%04Xu   /* aur.%s.%s */"%(name,base+i,app,s))
        inc.append('    { 0x%04Xu, "%s/aur.%s.%s" },'%(base+i,app,app,s))
        n+=1
    h.append("")
inc.append("};")
open(HDR,"w",encoding="utf-8",newline="\n").write("\n".join(h)+"\n")
open(INC,"w",encoding="utf-8",newline="\n").write("\n".join(inc)+"\n")
print("wrote header + inc with",n,"ids")
